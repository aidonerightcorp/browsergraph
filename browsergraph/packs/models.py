"""Six model families on identical inputs, and the answer that depends on the data.

The question "which model should we use" is usually settled by preference and
then defended by a benchmark run afterwards. This pack makes the family a
**candidate for one step** — everything upstream of it identical, everything
downstream identical — so the comparison measures the family and nothing else.

    from browsergraph import packs
    print(packs.get("models").solve().text())

Two data-generating processes, six families, RMSE on held-out rows — lower is
better, and `removed` is the fraction of the null control's error the family
actually got rid of. Measured, by a test that runs every route:

    family          linear truth  removed    threshold truth  removed
    fit.constant         73.8        —             54.6          —
    fit.linear            5.2       93%            33.2         39%
    fit.mlp               7.4       90%            19.8         64%
    fit.boosted          15.5       79%            19.5         64%
    fit.tree             39.6       46%            28.7         47%
    fit.attention        43.1       42%            37.2         32%

**There is no winner column.** The linear model removes 93% of the error on data
generated by an additive rule and 39% on data generated by a threshold and an
interaction — where boosted trees and a small network remove 64%. Both results
are obvious in hindsight and neither is knowable from the model list. Any
ranking of families that does not name the data-generating process is a ranking
of somebody's datasets.

`fit.constant` is the null control and the most important row in the table. It
predicts the training mean and nothing else, so a family that does not clearly
beat it has learned nothing — and **the number to beat is different for each
dataset** (73.8 and 54.6), which is why an absolute RMSE threshold carried
between projects means nothing at all. `compare.interval` therefore reports
every score against the constant with a bootstrap interval, and will say "this
decision does not matter" rather than crown a winner on a difference inside the
noise.

`fit.attention` is a single head over the columns — learned query, per-column
keys and values, softmax weights — and it is **fifth of six on both datasets**.
That is the expected and correct result at this size, and it is in the pack for
that reason: on a few hundred rows of tabular data a regularised linear model
and boosted trees are the honest baselines, and an attention model that beat
them here would be evidence of a bug rather than of progress.

Two findings fell out of building this and are documented where they happened
rather than smoothed away. A **depth-three tree scored worse than the null
control** on the threshold data, because one-hot encoding drops a reference
level and the tree then needs two splits to isolate the dropped category — the
encoding a linear model requires is not the encoding a tree requires. And
**boosting depth-one stumps is an additive model**, so it could not express the
size-and-kind interaction any better than the linear fit could; the base learner
is at depth two for that reason, which is a decision and not a default.

`prepare` is a single step shared by every family, which is the discipline the
whole comparison rests on. Its two candidates differ only in whether the numeric
columns are standardised, and the statistics come from the training half — the
transformer travels with the fold, so nothing downstream can recompute them
against the rows it is being scored on.

Standard library: Gaussian elimination for the linear fit, greedy
variance-reduction splits for the tree, gradient descent by hand for the two
networks. No numpy, seeded throughout.
"""
