def beats_the_null(run) -> tuple[bool, float]:
    """How much of the null baseline's error the family removed.

    Expressed as a fraction so the two datasets and the two metrics are on one
    scale — an absolute RMSE is not comparable across either, and a leaderboard
    that mixes them is comparing the difficulty of the data.
    """
    if not run.ok:
        return False, 0.0
    report = run.output("compare")
    baseline = report["baseline"] or 1.0
    removed = max(0.0, report["beats_null_by"] / baseline)
    return report["beats_null_by"] > 0, removed
